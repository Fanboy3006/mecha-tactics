def over(rows, patch):
    out = []
    for r, p in zip(rows, patch):
        out.append(''.join(('.' if pc == '_' else pc) if pc != '.' else rc for rc, pc in zip(r, p)))
    return out
def sym(patch):   # 把补丁左半边镜像到右半边（右半边原来的内容保留）
    out = []
    for r in patch:
        L = r[:10]; out.append(L + ''.join(c if c != '.' else r[10+i] for i, c in enumerate(L[::-1])))
    return out
